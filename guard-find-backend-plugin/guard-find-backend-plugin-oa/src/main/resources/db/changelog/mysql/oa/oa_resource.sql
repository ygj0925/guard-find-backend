    `end_time`             datetime      NOT NULL                    COMMENT '用车结束',
    `status`               varchar(20)   NOT NULL                    COMMENT '状态（APPROVING/PENDING_DISPATCH/DISPATCHED/IN_USE/RETURNED/CANCELLED/CLOSED/EXPIRED），DISPATCHED 与 IN_USE 占用车辆与司机',
    `vehicle_id`           bigint(20)    DEFAULT NULL                COMMENT '指派车辆',
    `driver_id`            bigint(20)    DEFAULT NULL                COMMENT '指派司机',
    `dispatch_request_id`  varchar(64)   DEFAULT NULL                COMMENT '调度幂等请求号',
    `dispatch_by`          bigint(20)    DEFAULT NULL                COMMENT '调度人',
    `dispatch_time`        datetime      DEFAULT NULL                COMMENT '调度时间',
    `dispatch_remark`      varchar(500)  DEFAULT NULL                COMMENT '调度备注',
    `depart_request_id`    varchar(64)   DEFAULT NULL                COMMENT '出车幂等请求号',
    `depart_time`          datetime      DEFAULT NULL                COMMENT '出车登记时间',
    `start_mileage`        int           DEFAULT NULL                COMMENT '出车里程',
    `return_request_id`    varchar(64)   DEFAULT NULL                COMMENT '归还幂等请求号',
    `return_time`          datetime      DEFAULT NULL                COMMENT '归还登记时间',
    `end_mileage`          int           DEFAULT NULL                COMMENT '归还里程',
    `fuel_cost`            decimal(12,2) DEFAULT NULL                COMMENT '油费/电费',
    `toll_cost`            decimal(12,2) DEFAULT NULL                COMMENT '路桥停车费',
    `other_cost`           decimal(12,2) DEFAULT NULL                COMMENT '其他费用',
    `return_remark`        varchar(500)  DEFAULT NULL                COMMENT '归还备注',
    `exec_by`              bigint(20)    DEFAULT NULL                COMMENT '最近一次出车/归还登记人',
    `cancel_by`            bigint(20)    DEFAULT NULL                COMMENT '取消人',
    `cancel_time`          datetime      DEFAULT NULL                COMMENT '取消时间',
    `cancel_reason`        varchar(500)  DEFAULT NULL                COMMENT '取消原因',
    `create_time`          datetime      NOT NULL                    COMMENT '创建时间',
    `update_time`          datetime      DEFAULT NULL                COMMENT '修改时间',
    PRIMARY KEY (`id`),
    UNIQUE INDEX `uk_tenant_application` (`tenant_id`, `application_id`),
    UNIQUE INDEX `uk_tenant_dispatch_request` (`tenant_id`, `dispatch_request_id`),
    UNIQUE INDEX `uk_tenant_depart_request` (`tenant_id`, `depart_request_id`),
    UNIQUE INDEX `uk_tenant_return_request` (`tenant_id`, `return_request_id`),
    INDEX `idx_tenant_status` (`tenant_id`, `status`, `id`),
    INDEX `idx_tenant_vehicle_time` (`tenant_id`, `vehicle_id`, `status`, `start_time`),
    INDEX `idx_tenant_driver_time` (`tenant_id`, `driver_id`, `status`, `start_time`),
    INDEX `idx_tenant_applicant` (`tenant_id`, `applicant_id`, `id`),
    INDEX `idx_status_end` (`status`, `end_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='OA 用车申请（审批通过后调度指派，出车与归还单独登记）';
