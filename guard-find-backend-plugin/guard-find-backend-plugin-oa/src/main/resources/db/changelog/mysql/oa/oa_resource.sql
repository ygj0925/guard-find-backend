    `destination`          varchar(200)  NOT NULL                    COMMENT '目的地',
    `passengers`           int           NOT NULL                    COMMENT '乘车人数',
    `need_driver`          tinyint(1)    NOT NULL DEFAULT 0          COMMENT '是否需要司机',
