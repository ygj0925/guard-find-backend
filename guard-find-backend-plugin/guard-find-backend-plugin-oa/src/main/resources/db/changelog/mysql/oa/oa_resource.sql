    `booker_id`            bigint(20)    NOT NULL                    COMMENT '预订人',
    `subject`              varchar(200)  NOT NULL                    COMMENT '会议主题',
    `start_time`           datetime      NOT NULL                    COMMENT '开始时间',
    `end_time`             datetime      NOT NULL                    COMMENT '结束时间',
    `attendees`            int           NOT NULL                    COMMENT '参会人数',
    `status`               varchar(20)   NOT NULL                    COMMENT '状态（APPROVING/BOOKED/CANCELLED/CLOSED/EXPIRED），APPROVING 与 BOOKED 占用时段',
    `cancel_by`            bigint(20)    DEFAULT NULL                COMMENT '取消人',
    `cancel_time`          datetime      DEFAULT NULL                COMMENT '取消时间',
    `cancel_reason`        varchar(500)  DEFAULT NULL                COMMENT '取消原因',
    `create_time`          datetime      NOT NULL                    COMMENT '创建时间',
    `update_time`          datetime      DEFAULT NULL                COMMENT '修改时间',
    PRIMARY KEY (`id`),
    UNIQUE INDEX `uk_tenant_application` (`tenant_id`, `application_id`),
