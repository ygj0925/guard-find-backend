--comment: 会议车辆：会议室与预订（区间冲突在锁住会议室后校验，审批中的预订到开始时间超时释放）、车辆/司机/维保与用车申请（审批通过后由调度指派，出车/归还/费用单独登记、按请求号幂等）

CREATE TABLE IF NOT EXISTS `oa_meeting_room` (
    `id`                   bigint(20)    AUTO_INCREMENT              COMMENT 'ID',
    `tenant_id`            bigint(20)    NOT NULL DEFAULT 0          COMMENT '租户ID',
    `code`                 varchar(32)   NOT NULL                    COMMENT '会议室编码',
    `name`                 varchar(100)  NOT NULL                    COMMENT '名称',
    `location`             varchar(200)  DEFAULT NULL                COMMENT '位置',
    `capacity`             int           NOT NULL                    COMMENT '容纳人数',
    `need_approval`        tinyint(1)    NOT NULL DEFAULT 0          COMMENT '是否需审批（需审批的只能经 OA 申请预订）',
    `status`               varchar(20)   NOT NULL DEFAULT 'ENABLED'  COMMENT '状态（ENABLED/DISABLED）',
    `remark`               varchar(500)  DEFAULT NULL                COMMENT '备注',
    `version`              int           NOT NULL DEFAULT 0          COMMENT '乐观锁版本',
    `create_user`          bigint(20)    NOT NULL                    COMMENT '创建人',
    `create_time`          datetime      NOT NULL                    COMMENT '创建时间',
    `update_user`          bigint(20)    DEFAULT NULL                COMMENT '修改人',
    `update_time`          datetime      DEFAULT NULL                COMMENT '修改时间',
    PRIMARY KEY (`id`),
    UNIQUE INDEX `uk_tenant_code` (`tenant_id`, `code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='OA 会议室';

